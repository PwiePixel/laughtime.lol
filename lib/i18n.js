export const dictionaries = { en, de };

export function translate(lang, key, vars) {
  const dict = dictionaries[lang] || en;
  let s = dict[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

